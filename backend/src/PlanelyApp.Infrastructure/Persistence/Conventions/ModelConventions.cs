using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Metadata.Internal;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;
using PlanelyApp.Domain.SeedWork;
using PlanelyApp.Infrastructure.Persistence.Interceptors;

namespace PlanelyApp.Infrastructure.Persistence.Conventions;

/// <summary>
/// Rules that apply to the whole model, so no entity configuration has to repeat them.
/// They run after the entity configurations, over everything that was mapped.
/// </summary>
internal static class ModelConventions
{
    private const int EnumColumnLength = 30;

    internal static void ApplyPlanelyConventions(this ModelBuilder modelBuilder)
    {
        modelBuilder.IgnoreDomainEvents();
        modelBuilder.AddAuditProperties();
        modelBuilder.StoreEnumsAsText();
        modelBuilder.UseStrictUtcDateTimes();
        modelBuilder.GenerateGuidKeysInTheDomain();

        // Last: the shadow properties above must exist, and tables must be named before columns.
        modelBuilder.UseSnakeCaseNames();
    }

    private static List<IMutableEntityType> AggregateRoots(this ModelBuilder modelBuilder) =>
        modelBuilder.Model.GetEntityTypes()
            .Where(entityType => entityType.BaseType is null && typeof(AggregateRoot).IsAssignableFrom(entityType.ClrType))
            .ToList();

    // Domain events live in memory until they are dispatched; they are never columns or tables.
    private static void IgnoreDomainEvents(this ModelBuilder modelBuilder)
    {
        foreach (var root in modelBuilder.AggregateRoots())
        {
            modelBuilder.Entity(root.ClrType).Ignore(nameof(AggregateRoot.DomainEvents));
        }
    }

    private static void AddAuditProperties(this ModelBuilder modelBuilder)
    {
        foreach (var root in modelBuilder.AggregateRoots())
        {
            var entity = modelBuilder.Entity(root.ClrType);
            entity.Property<DateTime>(AuditProperties.CreatedAt);
            entity.Property<DateTime>(AuditProperties.UpdatedAt);
        }
    }

    private static void StoreEnumsAsText(this ModelBuilder modelBuilder)
    {
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            foreach (var property in entityType.GetProperties())
            {
                var type = Nullable.GetUnderlyingType(property.ClrType) ?? property.ClrType;

                if (!type.IsEnum || property.GetValueConverter() is not null)
                {
                    continue;
                }

                var converterType = typeof(EnumToStringConverter<>).MakeGenericType(type);

                // The constructor has one optional parameter, so Activator needs it passed explicitly.
                property.SetValueConverter((ValueConverter)Activator.CreateInstance(converterType, new object?[] { null })!);
                property.SetMaxLength(EnumColumnLength);
            }
        }
    }

    private static void UseStrictUtcDateTimes(this ModelBuilder modelBuilder)
    {
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            foreach (var property in entityType.GetProperties())
            {
                if (property.GetValueConverter() is not null)
                {
                    continue;
                }

                if (property.ClrType == typeof(DateTime))
                {
                    property.SetValueConverter(UtcDateTimeConverters.Required);
                    property.SetColumnType("datetime(6)");
                }
                else if (property.ClrType == typeof(DateTime?))
                {
                    property.SetValueConverter(UtcDateTimeConverters.Optional);
                    property.SetColumnType("datetime(6)");
                }
            }
        }
    }

    // The Domain creates the Guid (v7). "Never" tells EF the key is not generated by the store or by EF, so a new
    // child with its key already set is inserted. With the default, EF would treat it as an existing row and UPDATE it.
    private static void GenerateGuidKeysInTheDomain(this ModelBuilder modelBuilder)
    {
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            var key = entityType.FindPrimaryKey();

            if (key is null || key.Properties.Count != 1)
            {
                continue;
            }

            var property = key.Properties[0];

            if (property.ClrType == typeof(Guid))
            {
                property.ValueGenerated = ValueGenerated.Never;
            }
        }
    }

    private static void UseSnakeCaseNames(this ModelBuilder modelBuilder)
    {
        var entityTypes = modelBuilder.Model.GetEntityTypes().ToList();

        // Phase 1: tables. Column and index names are stored per table name, so every table is final first.
        foreach (var entityType in entityTypes)
        {
            var ownership = entityType.FindOwnership();
            var hasOwnTable = entityType.BaseType is null && (ownership is null || !ownership.IsUnique);

            // An owned type that shares its owner's table follows the owner; it must not get a table of its own.
            if (hasOwnTable && entityType.GetTableName() is { } tableName)
            {
                entityType.SetTableName(SnakeCase.From(tableName));
            }
        }

        // Phase 2: columns and indexes.
        foreach (var entityType in entityTypes)
        {
            if (StoreObjectIdentifier.Create(entityType, StoreObjectType.Table) is not { } table)
            {
                continue;
            }

            foreach (var property in entityType.GetProperties())
            {
                if (property.GetColumnName(table) is { } columnName)
                {
                    property.SetColumnName(SnakeCase.From(columnName), table);
                }
            }

            foreach (var index in entityType.GetIndexes())
            {
                if (index.GetDatabaseName(table) is { } indexName)
                {
                    index.SetDatabaseName(SnakeCase.From(indexName));
                }
            }
        }
    }
}